// 获取国家颜色类别
function getCountryClass(count) {
    if (count === 0) return '0';
    if (count === 1) return '1';
    if (count <= 3) return '2-3';
    if (count <= 5) return '4-5';
    return '6plus';
}

// 显示地图提示框
function showMapTooltip(countryName, countryToUniversities) {
    const tooltip = document.getElementById('mapTooltip');
    const tooltipCountry = document.getElementById('tooltipCountry');
    const tooltipUniversities = document.getElementById('tooltipUniversities');
    if (!tooltip || !tooltipCountry || !tooltipUniversities) {
        console.warn('地图提示框相关元素缺失');
        return;
    }
    
    const unis = countryToUniversities[countryName] || [];
    
    tooltipCountry.textContent = countryName + ` (${unis.length}所)`;
    
    if (unis.length === 0) {
        tooltipUniversities.innerHTML = '<p style="color: #999;">暂无该区域的高校数据</p>';
    } else {
        tooltipUniversities.innerHTML = unis
            .map(uni => `
                <div class="tooltip-university">
                    <span class="tooltip-rank">${uni.rank}</span>
                    <span class="tooltip-name">${uni.name}</span>
                </div>
            `)
            .join('');
    }
    
    tooltip.classList.add('active');
}

// 隐藏地图提示框
function hideMapTooltip() {
    const tooltip = document.getElementById('mapTooltip');
    if (tooltip) {
        tooltip.classList.remove('active');
    }
}
