// 生成筛选标签
function renderFilterTabs() {
    const tabsHTML = `
        <button class="filter-tab active" data-region="all">全部 (${universities.length})</button>
        ${Object.entries(regionStats)
            .sort((a, b) => b[1] - a[1])
            .map(([region, count]) => `
                <button class="filter-tab" data-region="${region}">${region} (${count})</button>
            `)
            .join('')}
    `;
    
    filterTabsContainer.innerHTML = tabsHTML;
    
    // 重新绑定筛选标签事件
    document.querySelectorAll('.filter-tab').forEach(tab => {
        tab.addEventListener('click', () => {
            document.querySelectorAll('.filter-tab').forEach(t => t.classList.remove('active'));
            tab.classList.add('active');
            currentRegion = tab.dataset.region;
            isExpanded = false;
            renderUniversities();
        });
    });
}

// 生成国家统计
function renderCountryStats() {
    if (!countryStatsContainer) {
        console.warn('未找到 countryStats 容器，跳过国家统计渲染');
        return;
    }

    const countryCount = {};
    
    universities.forEach(uni => {
        if (!countryCount[uni.country]) {
            countryCount[uni.country] = {
                count: 0,
                flag: uni.flag
            };
        }
        countryCount[uni.country].count++;
    });
    
    const statsHTML = Object.entries(countryCount)
        .sort((a, b) => b[1].count - a[1].count)
        .map(([country, data]) => `
            <div class="country-item">
                <span class="country-flag">${data.flag}</span>
                <span class="country-name">${country}</span>
                <span class="country-count">${data.count}所</span>
            </div>
        `)
        .join('');
    
    countryStatsContainer.innerHTML = statsHTML;
}

