// 初始化事件监听
function initEventListeners() {
    // 搜索框
    searchInput.addEventListener('input', (e) => {
        currentSearchTerm = e.target.value;
        renderUniversities();
    });

    // 模态框关闭
    modalClose.addEventListener('click', closeModal);
    modal.addEventListener('click', (e) => {
        if (e.target === modal) closeModal();
    });

    // ESC键关闭模态框
    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape' && modal.classList.contains('active')) {
            closeModal();
        }
    });
    
    // 展开/收起按钮
    const expandButton = document.getElementById('expandButton');
    if (expandButton) {
        expandButton.addEventListener('click', () => {
            const grid = document.getElementById('universitiesGrid');
            if (!grid) return;
            const isCollapsed = grid.classList.contains('collapsed');
            
            if (isCollapsed) {
                grid.classList.remove('collapsed');
                expandButton.innerHTML = '收起 <span class="arrow">↑</span>';
                isExpanded = true;
            } else {
                grid.classList.add('collapsed');
                expandButton.innerHTML = '展开查看更多 <span class="arrow">↓</span>';
                isExpanded = false;
                // 滚动到大学列表顶部
                document.getElementById('universities').scrollIntoView({ behavior: 'smooth' });
            }
        });
    }

    // 平滑滚动
    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', function (e) {
            e.preventDefault();
            const target = document.querySelector(this.getAttribute('href'));
            if (target) {
                target.scrollIntoView({
                    behavior: 'smooth',
                    block: 'start'
                });
            }
        });
    });
}

// 滚动动画
function initScrollAnimations() {
    const observerOptions = {
        threshold: 0.1,
        rootMargin: '0px 0px -100px 0px'
    };

    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.style.opacity = '1';
                entry.target.style.transform = 'translateY(0)';
            }
        });
    }, observerOptions);

    // 观察需要动画的元素
    document.querySelectorAll('.university-card, .about-card, .country-item').forEach(el => {
        el.style.opacity = '0';
        el.style.transform = 'translateY(30px)';
        el.style.transition = 'opacity 0.6s, transform 0.6s';
        observer.observe(el);
    });
}

// 卡片动画
function animateCards() {
    const cards = document.querySelectorAll('.university-card');
    cards.forEach((card, index) => {
        card.style.opacity = '0';
        card.style.transform = 'translateY(30px)';
        setTimeout(() => {
            card.style.transition = 'opacity 0.6s, transform 0.6s';
            card.style.opacity = '1';
            card.style.transform = 'translateY(0)';
        }, index * 50);
    });
}

